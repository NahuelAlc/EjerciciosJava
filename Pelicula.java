
public class Pelicula{

    String titulo;
    String director;
    int anioEstreno;
    double puntuacion;

    void Pelicula(String titulo, String director, int anioEstreno, double puntuacion) {
        this.titulo = titulo;
        this.director = director;
        this.anioEstreno = anioEstreno;
        this.puntuacion = puntuacion;
    }
}